"""Benchmark runs on HF Jobs, recorded so they can be read and re-run exactly.

A benchmark is not a test: there is no pass/fail, the output is numbers and
plots, and the only thing that makes it worth anything is that you can say
precisely what produced it. So every run here is stored as a *recipe* —
script source, dependencies, image, flavor, PR commit, env — hashed into a
short id. Two runs with the same recipe hash are the same experiment; the UI
says so, and re-running one re-submits the recipe byte for byte.

The script is submitted through `hf jobs uv run` (what you'd type by hand)
wrapped in a small prelude that:
  - prints BENCH_META: python, platform, GPU, resolved package versions;
  - chdir's into $BENCH_OUT, so a plain plt.savefig("x.png") lands somewhere
    we collect without the script knowing about any of this;
  - uploads whatever ended up there to a Hub dataset and prints BENCH_ARTIFACTS.

Results come back two ways, both read straight from the immutable job log:
JSON printed by the script (JSON_BEGIN/END, BENCH_JSON, or a ```json fence)
and the uploaded files. Nothing is cached anywhere that can drift from it.
"""
import ast
import base64
import hashlib
import json
import re
import secrets
import subprocess
import time
from pathlib import Path

import repo_manager

BENCH_DIR = repo_manager.REPOS_DIR / ".bench"
OUT_DIR = "/tmp/bench-out"

# Printed by the prelude/epilogue; the UI parses these out of the job log.
META_MARK = "BENCH_META "
ARTIFACTS_MARK = "BENCH_ARTIFACTS "
PLAN_MARK = "BENCH_PLAN "


# ── recipe ───────────────────────────────────────────────────────────────────

def recipe_hash(script, deps, image, flavor, env, commit):
    """Short id over everything that changes the numbers — and nothing else.

    Deliberately excludes the job id, the timeout and the submission time: a
    rerun that only waits longer is still the same experiment.
    """
    payload = json.dumps({
        "script": script, "deps": sorted(deps or []), "image": image or "",
        "flavor": flavor, "env": dict(sorted((env or {}).items())), "commit": commit or "",
    }, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode()).hexdigest()[:6]


# ── the wrapper we actually submit ───────────────────────────────────────────

PEP723 = re.compile(r"^# /// script\s*$.*?^# ///\s*$", re.M | re.S)


def _split_header(src):
    """Pull a PEP 723 header off the script so the wrapper can re-declare it.

    `uv run` reads the header of the file it is handed, which is the wrapper,
    not the embedded source — so the script's own dependency block has to be
    copied up or its deps silently vanish.
    """
    m = PEP723.search(src)
    return (m.group(0), src[:m.start()] + src[m.end():]) if m else ("", src)


def _merge_header(header, extra_deps):
    """Return a PEP 723 header carrying the script's deps plus ours."""
    deps = list(extra_deps)
    if header:
        m = re.search(r"^#\s*dependencies\s*=\s*\[(.*?)\]", header, re.M | re.S)
        if m:
            body = re.sub(r"^#\s?", "", m.group(1), flags=re.M)
            try:
                deps = json.loads("[" + body.replace("'", '"') + "]") + deps
            except json.JSONDecodeError:
                pass  # unparseable header: keep it verbatim below and add ours
            else:
                header = ""
    seen, uniq = set(), []
    for d in deps:
        if d not in seen:
            seen.add(d); uniq.append(d)
    block = ("# /// script\n# dependencies = [\n"
             + "".join(f"#     {json.dumps(d)},\n" for d in uniq) + "# ]\n# ///")
    return (header + "\n" + block) if header else block


def build_wrapper(src, deps, artifacts_repo, artifacts_path, manifest):
    """The file handed to `hf jobs uv run`: prelude + the script + upload."""
    header, body = _split_header(src)
    full = _merge_header(header, ["huggingface_hub"] + list(deps or []))
    b64 = base64.b64encode(body.encode()).decode()
    meta = json.dumps(manifest, separators=(",", ":"))
    return f'''{full}
# ---------------------------------------------------------------------------
# Generated by gh-codepilot. The benchmark script is embedded verbatim below
# and run as __main__; everything around it only records and collects.
# ---------------------------------------------------------------------------
import base64, json, os, platform, sys, traceback

OUT = {OUT_DIR!r}
os.makedirs(OUT, exist_ok=True)
os.environ.setdefault("MPLBACKEND", "Agg")
os.environ["BENCH_OUT"] = OUT

RECIPE = json.loads({meta!r})


def _packages():
    try:
        from importlib.metadata import distributions
        return {{d.metadata["Name"]: d.version for d in distributions() if d.metadata.get("Name")}}
    except Exception:
        return {{}}


def _gpu():
    try:
        import torch
        if not torch.cuda.is_available():
            return {{"torch": torch.__version__, "cuda": False}}
        return {{"torch": torch.__version__, "cuda": torch.version.cuda,
                "device": torch.cuda.get_device_name(0), "count": torch.cuda.device_count(),
                "capability": ".".join(map(str, torch.cuda.get_device_capability(0)))}}
    except Exception:
        return {{}}


print("{META_MARK}" + json.dumps({{"recipe": RECIPE, "python": sys.version.split()[0],
      "platform": platform.platform(), "gpu": _gpu(), "packages": _packages()}}), flush=True)

# Relative paths in the script (plt.savefig("x.png"), open("results.json", "w"))
# resolve inside the collected directory without the script knowing.
os.chdir(OUT)
sys.argv = ["bench.py"]
rc = 0
try:
    exec(compile(base64.b64decode({b64!r}).decode(), "bench.py", "exec"),
         {{"__name__": "__main__", "__file__": "bench.py"}})
except SystemExit as e:
    rc = int(e.code or 0)
except BaseException:
    traceback.print_exc()
    rc = 1

files = sorted(
    os.path.relpath(os.path.join(dirpath, f), OUT)
    for dirpath, _, names in os.walk(OUT) for f in names
)
info = {{"files": files, "repo": {artifacts_repo!r}, "path": {artifacts_path!r}, "uploaded": False}}
if files and {bool(artifacts_repo)!r}:
    try:
        from huggingface_hub import HfApi
        api = HfApi()
        api.create_repo({artifacts_repo!r}, repo_type="dataset", private=True, exist_ok=True)
        api.upload_folder(folder_path=OUT, repo_id={artifacts_repo!r}, repo_type="dataset",
                          path_in_repo={artifacts_path!r})
        info["uploaded"] = True
    except Exception as e:
        info["error"] = f"{{type(e).__name__}}: {{e}}"[:300]
print("{ARTIFACTS_MARK}" + json.dumps(info), flush=True)
sys.exit(rc)
'''


# ── submit ───────────────────────────────────────────────────────────────────

def _job_label(repo, number):
    return f"gh-codepilot={repo.replace('/', '--')}--{number}"


def _local_run(cmd, timeout=60):
    """Default runner; app.py passes its eventlet-safe one instead."""
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return None


def submit(repo, number, *, name, script, deps, flavor, timeout, env, commit,
           image=None, artifacts_repo="", run=_local_run):
    """Submit one benchmark run; returns (manifest, error)."""
    BENCH_DIR.mkdir(parents=True, exist_ok=True)
    rh = recipe_hash(script, deps, image, flavor, env, commit)
    slug = repo.replace("/", "--")
    apath = f"{slug}/pr-{number}/{rh}-{time.strftime('%Y%m%d-%H%M%S')}"
    manifest = {"repo": repo, "number": int(number), "name": name, "recipe": rh,
                "flavor": flavor, "commit": commit, "deps": list(deps or []),
                "image": image or "", "env": dict(env or {}),
                "artifacts_repo": artifacts_repo, "artifacts_path": apath}
    wrapper = build_wrapper(script, deps, artifacts_repo, apath, manifest)

    tmp = BENCH_DIR / f"wrapper-{secrets.token_hex(4)}.py"
    tmp.write_text(wrapper)
    cmd = ["hf", "jobs", "uv", "run", "--flavor", flavor, "--timeout", timeout, "-d",
           "--label", _job_label(repo, number), "--label", "gh-codepilot-kind=bench",
           "--label", f"gh-codepilot-recipe={rh}",
           "--label", "gh-codepilot-bench=" + re.sub(r"[^A-Za-z0-9_-]", "_", name)[:60],
           "--secrets", "HF_TOKEN"]
    for k, v in (env or {}).items():
        cmd += ["-e", f"{k}={v}"]
    for d in deps or []:
        cmd += ["--with", d]
    if image:
        cmd += ["--image", image]
    cmd += [str(tmp)]
    r = run(cmd, timeout=150)
    tmp.unlink(missing_ok=True)
    if r is None:
        return None, "hf jobs run timed out"
    if r.returncode != 0:
        return None, (r.stderr or r.stdout or "submit failed").strip()[:400]
    m = re.search(r"\b([0-9a-f]{24})\b", r.stdout + r.stderr)
    if not m:
        return None, "submitted but no job id in output: " + (r.stdout or "")[:200]

    manifest.update(id=m.group(1), script=script, wrapper=wrapper, timeout=timeout,
                    submitted_at=time.time(),
                    # The argv minus our temp path, so the Setup tab can show a
                    # command that is actually runnable by hand.
                    command=cmd[:-1] + [f"{name}"])
    (BENCH_DIR / f"{m.group(1)}.json").write_text(json.dumps(manifest, indent=1))
    return manifest, None


def manifest(job_id):
    f = BENCH_DIR / f"{job_id}.json"
    if not f.exists():
        return None
    try:
        return json.loads(f.read_text())
    except json.JSONDecodeError:
        return None


def manifests(repo, number):
    """Every recorded benchmark for this PR, newest first."""
    out = []
    for f in BENCH_DIR.glob("*.json"):
        try:
            m = json.loads(f.read_text())
        except (json.JSONDecodeError, OSError):
            continue
        if m.get("repo") == repo and int(m.get("number", -1)) == int(number):
            out.append(m)
    return sorted(out, key=lambda m: m.get("submitted_at", 0), reverse=True)


# ── read results back out of the log ─────────────────────────────────────────

FENCE = re.compile(r"```json\s*\n(.*?)\n```", re.S)
PAIRED = re.compile(r"^JSON_BEGIN\s*$\n(.*?)^JSON_END\s*$", re.M | re.S)
NAMED = re.compile(r"^BENCH_JSON(?:\s+([\w.\-]+))?\s+(\{.*\}|\[.*\])\s*$", re.M)


def _tabular(value):
    """True when this is a list of flat records — the only thing we can chart."""
    return (isinstance(value, list) and value and all(isinstance(r, dict) for r in value)
            and all(not isinstance(v, (dict, list)) for r in value for v in r.values()))


def _collect(obj, label, datasets, facts):
    """Split one parsed JSON object into chartable tables and scalar facts."""
    if _tabular(obj):
        datasets.append({"name": label, "rows": obj})
    elif isinstance(obj, dict):
        for k, v in obj.items():
            if _tabular(v):
                datasets.append({"name": k, "rows": v})
            elif not isinstance(v, (dict, list)):
                facts[k] = v


def parse_log(text):
    """Pull meta, charts, artifacts and the run's own scalars out of a job log."""
    out = {"meta": None, "datasets": [], "facts": {}, "artifacts": None,
           "json_errors": [], "plan": None}
    for line in text.splitlines():
        if line.startswith(PLAN_MARK):
            try:
                out["plan"] = json.loads(line[len(PLAN_MARK):])
            except json.JSONDecodeError:
                pass
        elif line.startswith(META_MARK):
            try:
                out["meta"] = json.loads(line[len(META_MARK):])
            except json.JSONDecodeError:
                pass
        elif line.startswith(ARTIFACTS_MARK):
            try:
                out["artifacts"] = json.loads(line[len(ARTIFACTS_MARK):])
            except json.JSONDecodeError:
                pass

    blocks = ([(None, b) for b in PAIRED.findall(text)]
              + [(n, b) for n, b in NAMED.findall(text)]
              + [(None, b) for b in FENCE.findall(text)])
    for i, (name, raw) in enumerate(blocks):
        try:
            obj = json.loads(raw)
        except json.JSONDecodeError as e:
            out["json_errors"].append(str(e)[:120])
            continue
        _collect(obj, name or (f"results {i + 1}" if len(blocks) > 1 else "results"),
                 out["datasets"], out["facts"])
    return out


IMAGE_EXT = {".png", ".jpg", ".jpeg", ".gif", ".svg", ".webp"}
CACHE_DIR = BENCH_DIR / "artifacts"


def artifact_files(job_id, log_info, manifest_):
    """What a run uploaded. The list comes from the log the run itself wrote.

    No repo listing call: the run printed exactly what it collected, so the
    log stays the single source of truth and an empty list means empty, not
    "the Hub was slow".
    """
    art = log_info or {}
    repo_id = art.get("repo") or (manifest_ or {}).get("artifacts_repo") or ""
    path = art.get("path") or (manifest_ or {}).get("artifacts_path") or ""
    out = []
    for name in art.get("files") or []:
        out.append({"name": name, "image": Path(name).suffix.lower() in IMAGE_EXT,
                    "src": f"/api/bench/artifact?id={job_id}&file={name}"})
    return {"files": sorted(out, key=lambda a: (not a["image"], a["name"])),
            "repo": repo_id, "path": path, "uploaded": bool(art.get("uploaded")),
            "error": art.get("error", ""),
            "hub_url": f"https://huggingface.co/datasets/{repo_id}/tree/main/{path}"
                       if repo_id and path else ""}


def fetch_artifact(job_id, name, run=_local_run):
    """Download one uploaded file into a local cache and return its path.

    Proxied rather than linked because the results dataset is private by
    default, so the browser has no token to fetch it with.
    """
    m = manifest(job_id)
    if not m or not m.get("artifacts_repo") or not m.get("artifacts_path"):
        return None
    if ".." in name or name.startswith("/"):
        return None
    remote = f"{m['artifacts_path'].rstrip('/')}/{name}"
    local = CACHE_DIR / job_id / name
    if local.exists():
        return local
    local.parent.mkdir(parents=True, exist_ok=True)
    r = run(["hf", "download", m["artifacts_repo"], remote, "--repo-type", "dataset",
             "--local-dir", str(CACHE_DIR / job_id / "_dl")], timeout=240)
    if r is None or r.returncode != 0:
        return None
    got = CACHE_DIR / job_id / "_dl" / remote
    if not got.exists():
        return None
    got.replace(local)
    return local


# ── Reviewing a benchmark before it burns GPU hours ──────────────────────────
# The script is usually written by Claude, not by hand, so the question the UI
# has to answer is "did it design this correctly?". Two separate answers:
#
#   declared  — a BENCH_PLAN the script states about itself. Convenient, and
#               entirely unverified: a script can claim a warmup it never runs.
#   checked   — what parsing the source actually finds. Fewer claims, but each
#               one is evidence. These are kept apart in the API and in the UI
#               so a claim is never mistaken for a check.

import ast

def extract_plan(src):
    """A literal `BENCH_PLAN = {...}` assignment, if the script declares one."""
    try:
        tree = ast.parse(src)
    except SyntaxError:
        return None
    for node in ast.walk(tree):
        if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "BENCH_PLAN" for t in node.targets):
            try:
                return ast.literal_eval(node.value)
            except (ValueError, SyntaxError):
                return None
    return None


def _sweeps(tree):
    """`for n in (1, 2, 4)` / `for x in range(...)` — what the run varies."""
    out = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.For) or not isinstance(node.target, ast.Name):
            continue
        it = node.iter
        if isinstance(it, (ast.Tuple, ast.List, ast.Set)):
            try:
                vals = [ast.literal_eval(e) for e in it.elts]
            except (ValueError, SyntaxError):
                continue
            out.append({"var": node.target.id, "values": vals[:12], "n": len(vals)})
        elif isinstance(it, ast.Call) and isinstance(it.func, ast.Name) and it.func.id == "range":
            try:
                args = [ast.literal_eval(a) for a in it.args]
            except (ValueError, SyntaxError):
                continue
            rng = list(range(*args))
            out.append({"var": node.target.id, "values": rng[:12], "n": len(rng)})
    # One entry per distinct value-set, keyed first by variable then by the
    # values themselves: a plotting loop re-walking the same list (`for dt in
    # dtypes`) is the same sweep, not a second one.
    best = {}
    for s in out:
        if s["var"] not in best or s["n"] > best[s["var"]]["n"]:
            best[s["var"]] = s
    seen, uniq = {}, []
    for s in sorted(best.values(), key=lambda x: (-x["n"], -len(x["var"]))):
        key = json.dumps(s["values"], sort_keys=True, default=str)
        if key in seen:
            continue
        seen[key] = True; uniq.append(s)
    return uniq


def _calls(tree):
    """Every dotted call name in the script, e.g. {'torch.cuda.synchronize'}."""
    names = set()
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            continue
        f, parts = node.func, []
        while isinstance(f, ast.Attribute):
            parts.append(f.attr); f = f.value
        if isinstance(f, ast.Name):
            parts.append(f.id)
        if parts:
            names.add(".".join(reversed(parts)))
    return names


def audit_script(src):
    """Methodology checks read out of the source. Evidence, not claims.

    Every check is a source scan, so a `warn` means "not found here", which is
    not the same as "absent" — the UI says so rather than implying a verdict.
    """
    try:
        tree = ast.parse(src)
    except SyntaxError as e:
        return {"parse_error": f"line {e.lineno}: {e.msg}", "checks": [], "sweeps": [], "calls": []}

    calls = _calls(tree)
    has = lambda *subs: any(any(s in c for c in calls) for s in subs)
    low = src.lower()
    gpu = has("cuda", "torch") or "device" in low

    seeded = has("manual_seed", "default_rng", "seed") or bool(re.search(r"\bseed\b", low))

    def chk(id_, label, ok, detail, na=False):
        return {"id": id_, "label": label, "detail": detail,
                "status": "na" if na else ("ok" if ok else "warn")}

    checks = [
        chk("warmup", "Warms up before timing", "warmup" in low or "warm_up" in low,
            "a warmup pass is named in the source" if "warmup" in low or "warm_up" in low
            else "no 'warmup' anywhere — the first call usually pays compile/alloc cost and will dominate"),
        chk("repeat", "Repeats each measurement",
            bool(re.search(r"\b(reps|repeats?|iterations?|n_iter|num_runs|measurement\w*)\b", low)),
            "a repetition count is named" if re.search(r"\b(reps|repeats?|iterations?|n_iter|num_runs)\b", low)
            else "no repetition count found — a single sample of a GPU kernel is noise"),
        chk("sync", "Synchronises the GPU around timing",
            has("cuda.synchronize", "synchronize", "cuda.Event", "Event.elapsed_time"),
            "torch.cuda.synchronize / cuda.Event found" if has("cuda.synchronize", "synchronize", "cuda.Event")
            else "CUDA calls are async — without a synchronize (or cuda.Event) the timer measures launch, not work",
            na=not gpu),
        chk("clock", "Uses a monotonic timer",
            has("perf_counter", "perf_counter_ns", "cuda.Event", "monotonic") or not has("time.time"),
            "perf_counter / cuda.Event" if has("perf_counter", "cuda.Event")
            else "time.time() is wall-clock and can step backwards; prefer perf_counter or cuda.Event"),
        chk("seed", "Seeds the random state", seeded,
            "a seed is set, so reruns draw the same inputs" if seeded
            else "no seed — reruns draw different data and the numbers will not line up"),
        chk("correctness", "Checks the variants agree",
            has("allclose", "assert_close", "testing.assert_allclose", "array_equal"),
            "compares outputs between implementations" if has("allclose", "assert_close")
            else "nothing compares the implementations' outputs — a faster wrong answer is not a win"),
        chk("emits_json", "Emits a table the UI can chart",
            "JSON_BEGIN" in src or "BENCH_JSON" in src,
            "prints a JSON block" if "JSON_BEGIN" in src or "BENCH_JSON" in src
            else "no JSON_BEGIN/JSON_END block — results will only exist as log text"),
        chk("saves_plots", "Saves plot files", has("savefig", "write_image", "imsave"),
            "writes an image, which gets collected and uploaded" if has("savefig")
            else "no savefig — fine if the JSON table is enough"),
    ]
    return {"parse_error": "", "checks": checks, "sweeps": _sweeps(tree),
            "calls": sorted(calls)[:200]}
